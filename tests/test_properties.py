"""Property-based and fuzz tests for the parser, the port, and the screener.

The example-based suites pin specific expected behaviour. These tests state the
*properties* that behaviour has to satisfy for inputs nobody thought to write down,
because that is where a safety tool actually breaks: an input no one enumerated.

Three properties carry most of the weight:

  1. TOTALITY. `SqlParser.parse` and `port_grammar` are total over their input
     domains. They raise exactly one documented exception type and nothing else --
     no `AttributeError` from a malformed tree, no `RecursionError` escaping, no
     `KeyError` from a missing token. This is the fail-closed property from
     model.py: if analysis cannot complete, the caller must be able to catch that
     and report UNKNOWN, so an undeclared exception type is a real defect, not a
     cosmetic one.
  2. INVARIANCE. The parse of a statement does not depend on how it was spelled.
     Case, surrounding whitespace, a trailing semicolon and a trailing comment must
     not change the statement label. This is the observable face of the
     `caseInsensitive` fix: the original port rejected `select 1` while real Spark
     accepted it, and the reason nobody noticed is that the example tests were all
     written in uppercase.
  3. NO FALSE ALLOW. `screen()` never returns ALLOW for source it could not
     analyze, and `Report.verdict` never ranks a DENY below an UNKNOWN. The whole
     value proposition is that a green report means "we looked"; a property test
     over generated PySpark is the cheapest way to keep that true as the policy
     layer grows.

Fuzz inputs are generated by Hypothesis, plus a seeded `random` sweep for the
`port_grammar` totality check where structured generation would be beside the
point -- the point is that *arbitrary* bytes either parse or raise `PortError`.

Known source bugs are recorded as non-strict xfails at the bottom, following the
convention in tests/test_folding.py. Nothing under src/ is modified here.
"""
from __future__ import annotations

import random
import re
import string

import pytest
from hypothesis import HealthCheck, assume, given, settings
from hypothesis import strategies as st

from sparkscreen.grammar.parser import SqlParser, SqlSyntaxError, get_parser
from sparkscreen.grammar.port import PortError, port_grammar
from sparkscreen.grammar.spec import SPECS, GrammarSpec
from sparkscreen.model import UNKNOWN_REASONS, Verdict
from sparkscreen.screen import screen

pytestmark = pytest.mark.fuzz

# Parsing is CPU-bound and the ANTLR runtime is not fast, so the default Hypothesis
# deadline (200ms) would flake on a loaded machine. Correctness here is about which
# exception type escapes, not how fast it arrives.
settings.register_profile(
    "sparkscreen",
    deadline=None,
    max_examples=40,
    suppress_health_check=[HealthCheck.too_slow, HealthCheck.data_too_large],
)
settings.load_profile("sparkscreen")

KEYS = [s.key for s in SPECS]

# --------------------------------------------------------------------------- SQL corpus

#: Statements every pinned grammar accepts. Used as seeds for mutation and as the
#: base for invariance checks. Kept to constructs valid in both 3.5.1 and 4.0.
SEED_SQL = [
    "SELECT 1",
    "select a from t1 where a > 1 group by a having count(*) > 1 order by a limit 5",
    "with x as (select 1) select * from x",
    "drop table prod.users",
    "DROP TABLE IF EXISTS prod.users PURGE",
    "insert overwrite table prod.t select 1",
    "insert into t values (1)",
    "delete from t where id = 1",
    "alter table t add column b int",
    "create table t (a int) using parquet",
    "set spark.sql.shuffle.partitions=200",
    "show tables",
    "select cast(x as struct<a: int>) from t",
    "select a -> 'b' from t",
    "select /*+ BROADCAST(t) */ * from t",
    "select 'it''s quoted'",
    "explain select 1",
    "truncate table t",
]

_SQL_TEXT = st.sampled_from(SEED_SQL)

#: Fragments that stress the lexer: unterminated literals, bracketed comments,
#: dollar-quoting, unicode, embedded quotes, NUL-ish control characters.
_NOISE = st.sampled_from([
    "", " ", "\n", "\t", ";", " -- trailing", "\n/* c */", "/* unclosed",
    "'unterminated", '"', "$$", "`", "\x00", "é", "\U0001f600",
    "/*+ hint */", "$$x$$", "'a'||'b'", "/*", "*/", "\\",
])

#: Arbitrary text, for the totality property. Constrained to be short so the
#: RecursionError paths in the parser are reachable without a timeout.
_ARBITRARY_TEXT = st.text(max_size=60)

_PARSER_CACHE: dict[str, SqlParser] = {}


def _parser(key: str) -> SqlParser:
    if key not in _PARSER_CACHE:
        _PARSER_CACHE[key] = get_parser(key)
    return _PARSER_CACHE[key]


