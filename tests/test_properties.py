@given(key=st.sampled_from(KEYS))
def test_get_spec_round_trips_through_its_key(key):
    """PROPERTY: get_spec(get_spec(k).key) is the same spec object."""
    from sparkscreen.grammar.spec import get_spec

    assert get_spec(key).key == key
    assert get_spec(key) is get_spec(get_spec(key).key)


@given(version=st.sampled_from(sorted({v for s in SPECS for v in s.spark_versions})))
def test_spec_lookup_accepts_bare_and_v_prefixed_versions(version):
    """PROPERTY: `v3.5.1` and `3.5.1` resolve to the same pinned grammar.

    Spark version strings arrive with a `v` about half the time, from `spark-submit`
    output, from build files, and from humans typing into config.
    """
    from sparkscreen.grammar.spec import spec_for_spark_version

