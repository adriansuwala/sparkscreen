@pytest.mark.xfail(strict=False, reason=(
    "BUG (port.py:116): the docstring claims port_grammar 'asserts that no rewrite is "
    "left unused', but unused_rules is only recorded and port_to_python discards it. "
    "spark-3.5.1 has 6 unused lexer rewrites and 6 unused parser rewrites today."
))
def test_unused_rewrites_are_surfaced_propertywise():
    """PROPERTY: a rewrite that no longer matches any pinned grammar is reported.

    A Spark upgrade that drops a construct should not leave dead rewrites behind
    silently; the docstring says they are reported.
    """
    total = 0
    for spec in SPECS:
        for name in spec.files:
            result = port_grammar(
                spec.vendored_path(name).read_text(),
                is_lexer=name.endswith("Lexer"),
            )
            total += len(result.unused_rules)
    assert total == 0, f"{total} rewrites no longer match any pinned grammar"
