_PYSRC_SQL = st.sampled_from([
    'spark.sql("select 1")',
    'spark.sql("drop table prod.users")',
    'spark.sql("insert into t values (1)")',
    'spark.sql("select a from t where a > 1")',
    'spark.sql(f"select {x}")',
    'spark.sql("select " + x)',
    'df.createOrReplaceTempView("v")',
    'spark.sql("SET spark.sql.x=1")',
])


@given(src=st.text(max_size=200))
def test_screen_never_raises_on_arbitrary_text(src):
    """PROPERTY: screen() is total over arbitrary source text.

    It reports UNKNOWN for source it cannot analyze, so there must be no input that
    escapes as an unhandled exception. A crash here is a fail-open failure in the
    crudest sense: the caller gets no report at all.
    """
    try:
        report = screen(src)
    except Exception as e:  # noqa: BLE001
        pytest.fail(f"{type(e).__name__} escaped screen(): {e!r}\nsource={src!r}")
    assert report.verdict in tuple(Verdict)


@given(st.lists(_PYSRC_SQL, min_size=1, max_size=6))
def test_report_verdict_ranks_deny_above_unknown(statements):
    """PROPERTY: DENY > UNKNOWN > REVIEW > ALLOW, whatever the mix.

    Guards the aggregation bug model.py documents: deriving the verdict from the
    *reason* rather than the *verdict* made DELETE and MERGE -- which are
    `verdict=REVIEW, reason=DESTRUCTIVE_STATEMENT` -- report as ALLOW, so
    `DELETE FROM prod.users` was waved through.

    The order is total and the middle two are deliberately close: UNKNOWN outranks
    REVIEW because a file the screener could not read is the more urgent problem,
    but both refuse.
    """
    source = "import pyspark\n" + "\n".join(statements)
    report = screen(source)
    verdicts = {f.verdict for f in report.findings}
    if Verdict.DENY in verdicts:
        assert report.verdict is Verdict.DENY
    elif Verdict.UNKNOWN in verdicts:
        assert report.verdict is Verdict.UNKNOWN
    elif Verdict.REVIEW in verdicts:
        assert report.verdict is Verdict.REVIEW
    else:
        assert report.verdict is Verdict.ALLOW


@given(st.lists(_PYSRC_SQL, min_size=1, max_size=6))
def test_ok_is_equivalent_to_allow_with_no_findings(statements):
    """PROPERTY: `Report.ok` is True only for a clean ALLOW.

    The convenience predicate callers reach for must not be able to say "fine" while
    an analysis failure is sitting in the report.
    """
    report = screen("import pyspark\n" + "\n".join(statements))
    if report.ok:
        assert report.verdict is Verdict.ALLOW
        assert not report.analysis_failures
        assert all(f.verdict is Verdict.ALLOW for f in report.findings)


@given(st.lists(_PYSRC_SQL, min_size=1, max_size=6))
def test_unresolved_sinks_never_yield_allow(statements):
    """PROPERTY: an UNRESOLVED_DYNAMIC_SQL finding forces at least UNKNOWN.

    `spark.sql(f"select {x}")` cannot be folded, so it cannot be parsed, so it
    cannot be screened. The only safe verdict is UNKNOWN -- reporting ALLOW would
    be telling the user their dynamic SQL is fine when nobody ever looked at it.
    """
    assume(any("{" in s or "+" in s for s in statements))
    report = screen("import pyspark\nx = input()\n" + "\n".join(statements))
    assert report.verdict is not Verdict.ALLOW, (
        f"ALLOW with a dynamic sink: {report.summary()}"
    )


@given(st.lists(_PYSRC_SQL, min_size=1, max_size=6))
def test_analysis_failures_are_all_unknown_verdicts(statements):
    """PROPERTY: a finding whose reason means "we could not analyze" is UNKNOWN.

    `is_analysis_failure` and `is_unknown` are independent axes in the model, but
    the *first* one must never be true for a finding that claims to be a decision.
    """
    report = screen("import pyspark\n" + "\n".join(statements))
    for finding in report.analysis_failures:
        assert finding.reason in UNKNOWN_REASONS
        assert finding.is_unknown, (
            f"reason={finding.reason} is an analysis failure but verdict is "
            f"{finding.verdict}"
        )


@given(key=st.sampled_from(KEYS), sql=_SQL_TEXT)
def test_screening_is_deterministic(key, sql):
    """PROPERTY: screening the same source twice gives the same verdict.

    A policy decision that depends on call order or global state would be
    untestable in production and unauditable after the fact.
    """
    source = f'import pyspark\nspark.sql("{sql}")\n'
    first = screen(source, spec=key)
    second = screen(source, spec=key)
    assert first.verdict is second.verdict
    assert [f.to_dict() for f in first.findings] == [f.to_dict() for f in second.findings]


